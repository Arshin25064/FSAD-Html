CREATE FUNCTION get_student_name(vtu VARCHAR(15))
RETURNS VARCHAR(50)
DETERMINISTIC
BEGIN
   DECLARE sname VARCHAR(50);
   SELECT name INTO sname FROM Student WHERE vtu_no = vtu;
   RETURN sname;
END //

